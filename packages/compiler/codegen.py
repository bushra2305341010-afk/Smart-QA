"""Compiled case → readable Playwright (Python) test file (pillar P6: open artifacts).

The file is generated from the same `CompiledCase` the runner executes, so what a user downloads
is what ran. Values are emitted with `repr()` (never string-pasted), secrets stay placeholders
read from the environment at run time, and `check_imports` rejects any import outside the
allow-list (sector 05 bug locator: "Compiled test fails import check").
"""

from __future__ import annotations

import ast
import re

from packages.contracts.run import CompiledAction, CompiledCase, Locator

ALLOWED_IMPORTS = frozenset({"os", "re", "playwright.sync_api"})
SECRET = re.compile(r"^\{\{secret:([a-z0-9_]{1,40})\}\}$")


class ImportNotAllowedError(ValueError):
    pass


def secret_env(name: str) -> str:
    return f"SAQ_SECRET_{name.upper()}"


def _value(value: str | None) -> str:
    raw = value or ""
    m = SECRET.match(raw)
    return f"os.environ[{secret_env(m.group(1))!r}]" if m else repr(raw)


def _locator(loc: Locator | None) -> str:
    if loc is None:
        raise ValueError("action needs a locator")
    v = repr(loc.value)
    match loc.by:
        case "role":
            return f"page.get_by_role({(loc.role or 'button')!r}, name={v})"
        case "label":
            return f"page.get_by_label({v})"
        case "text":
            return f"page.get_by_text({v})"
        case "placeholder":
            return f"page.get_by_placeholder({v})"
        case "test_id":
            return f"page.get_by_test_id({v})"
        case _:
            return f"page.locator({v})"


def _line(a: CompiledAction) -> str:
    match a.kind:
        case "goto":
            target = a.value or "/"
            url = repr(target) if target.startswith("http") else f"BASE_URL + {target!r}"
            return f"page.goto({url})"
        case "click":
            return f"{_locator(a.locator)}.first.click()"
        case "fill":
            return f"{_locator(a.locator)}.fill({_value(a.value)})"
        case "select":
            return f"{_locator(a.locator)}.select_option({_value(a.value)})"
        case "check":
            return f"{_locator(a.locator)}.check()"
        case "press":
            return f"page.keyboard.press({(a.value or 'Enter')!r})"
        case "expect_url":
            return f"expect(page).to_have_url(re.compile(re.escape({(a.value or '')!r})))"
        case "expect_hidden":
            return f"expect({_locator(a.locator)}.first).to_be_hidden()"
        case _:  # expect_text / expect_visible
            return f"expect({_locator(a.locator)}.first).to_be_visible()"


def _func_name(code: str) -> str:
    return "test_" + (re.sub(r"[^a-z0-9]+", "_", code.lower()).strip("_") or "case")


def render(case: CompiledCase, base_url: str, expected_text: str, quote: str | None) -> str:
    def doc(text: str) -> str:
        return text.replace("\\", "\\\\").replace('"""', "'''")

    lines = [
        f'"""{doc(case.code)}: generated by Smart Autonomous QA. Do not edit; re-compile.',
        "",
        f"Expected: {doc(expected_text)}",
        f"Source quote: {doc(quote) if quote else '(none: the Judge reports Unable to Verify)'}",
        '"""',
        "",
        "import os",
        "import re",
        "",
        "from playwright.sync_api import Page, expect",
        "",
        f"BASE_URL = os.environ.get('SAQ_BASE_URL', {base_url.rstrip('/')!r})",
        "",
        "",
        f"def {_func_name(case.code)}(page: Page) -> None:",
    ]
    step = 0
    for a in case.actions:
        if a.step_n != step:
            step = a.step_n
            lines.append(f"    # step {step}")
        suffix = "  # expected result (cited)" if a.expected else ""
        lines.append(f"    {_line(a)}{suffix}")
    for n in case.unparsed_steps:
        lines.append(f"    # step {n}: not compiled (manual step); the case cannot pass on its own")
    source = "\n".join(lines) + "\n"
    check_imports(source)
    return source


def check_imports(source: str) -> None:
    for node in ast.walk(ast.parse(source)):
        names: list[str] = []
        if isinstance(node, ast.Import):
            names = [a.name for a in node.names]
        elif isinstance(node, ast.ImportFrom):
            names = [node.module or ""]
        bad = [n for n in names if n not in ALLOWED_IMPORTS]
        if bad:
            raise ImportNotAllowedError(f"import not allowed in compiled tests: {', '.join(bad)}")
